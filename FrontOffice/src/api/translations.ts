export type TranslationKey = keyof typeof translations.en;

export function t(key: TranslationKey, language: string = 'en', params?: Record<string, string | number>): string {
  const lang = translations[language as keyof typeof translations];
  let text = '';
  if (lang && lang[key]) {
    text = lang[key];
  } else if (translations.en[key]) {
    text = translations.en[key];
  } else {
    return key;
  }
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
}

export function useTranslation(language?: string) {
  // Lire depuis le contexte React si disponible (via localStorage comme fallback)
  const lang = language || localStorage.getItem('hrbrain_language') || 'en';
  return (key: TranslationKey, params?: Record<string, string | number>) => t(key, lang, params);
}